def default_roster():
    roster = deepcopy(list(AGENT_ROSTER))
    for agent in roster:
        agent.update(display_name=agent["default_name"], enabled=True, custom_do=[], custom_dont=[], secret_refs=[])
    return roster

def validate_profile(profile):
    if not isinstance(profile, dict):
        return ["profile must be a mapping"]
    errors = []
    if not profile.get("id"): errors.append("stable id is required")
    if not str(profile.get("display_name", "")).strip(): errors.append("display_name is required")
    for field in ("custom_do", "custom_dont", "secret_refs"):
        if field in profile and not isinstance(profile[field], list): errors.append(field + " must be a list")
    if any(k in profile for k in ("secret_values", "api_key", "password")):
        errors.append("raw secrets must never be stored in an agent profile")
    return errors
