"""Who uses whom between the Workspace JS parts (modules/ws/*.js) -> docs/WORKSPACE_DEPS.md.

Maintenance plan M6 / step 2.1: tells the chart core apart from the side parts before splitting the build.
Static text match, not a JS parser: a name defined in part A and written in part B = "B uses A".
shortcut: method names are matched as `.name` (len >= 4) and can collide (e.g. two classes with `paint`); treat counts as a guide.
Run: python3 scripts/ws_deps.py   (rewrites docs/WORKSPACE_DEPS.md)
"""
import pathlib
import re
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parent.parent
WS = ROOT / "modules" / "ws"
TOP = re.compile(r"^(?:async\s+)?function\s+([A-Za-z_$][\w$]*)|^(?:const|let|var|class)\s+([A-Za-z_$][\w$]*)", re.M)
ATTR = re.compile(r"^([A-Za-z_$][\w$]*)\.(?:prototype\.)?([A-Za-z_$][\w$]*)\s*=", re.M)
METH = re.compile(r"^  (?:async\s+)?([A-Za-z_$][\w$]*)\s*\([^)]*\)\s*\{\s*$", re.M)
COMMENT = re.compile(r"//[^\n]*|/\*.*?\*/", re.S)


def scan():
    parts = {p.name: COMMENT.sub("", p.read_text(encoding="utf-8")) for p in sorted(WS.glob("*.js"))}
    names, methods = defaultdict(set), defaultdict(set)   # part -> defined globals / methods
    for n, src in parts.items():
        for a, b in TOP.findall(src):
            names[n].add(a or b)
        for obj, attr in ATTR.findall(src):
            methods[n].add(attr)
            names[n].add(obj) if obj not in {"window", "this"} and not any(obj in names[o] for o in parts if o != n) else None
        methods[n].update(METH.findall(src))
    uses = defaultdict(lambda: defaultdict(set))           # user -> provider -> names
    for user, src in parts.items():
        words = set(re.findall(r"[A-Za-z_$][\w$]*", src))
        dots = set(re.findall(r"\.([A-Za-z_$][\w$]*)", src))
        for prov in parts:
            if prov == user:
                continue
            hit = {x for x in names[prov] if len(x) >= 3 and x in words and x not in names[user]}
            hit |= {"." + m for m in methods[prov] if len(m) >= 4 and m in dots and m not in methods[user]}
            if hit:
                uses[user][prov] = hit
    return parts, names, methods, uses


def render(parts, names, methods, uses):
    used_by = defaultdict(set)
    for u, provs in uses.items():
        for p in provs:
            used_by[p].add(u)
    out = ["# Workspace parts - dependency map (generated)", "",
           "Generated by `python3 scripts/ws_deps.py` from `modules/ws/*.js` (static name match, not a parser; counts are a guide).",
           "Maintenance plan M6 / step 2.1. **Used by many = core; used by none = candidate for on-demand loading.**", "",
           "| Part | KB | Defines (globals / methods) | Used by (parts) | Uses (parts) |", "|---|---|---|---|---|"]
    for n in parts:
        kb = (WS / n).stat().st_size / 1024
        out.append(f"| `{n}` | {kb:.0f} | {len(names[n])} / {len(methods[n])} | {len(used_by[n])} | {len(uses[n])} |")
    out += ["", "## Details (part -> parts it uses, with up to 6 names)", ""]
    for n in parts:
        if uses[n]:
            out.append(f"- **`{n}`** uses: " + "; ".join(
                f"`{p}` ({', '.join(sorted(v)[:6])}{' ...' if len(v) > 6 else ''})" for p, v in sorted(uses[n].items())))
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    doc = render(*scan())
    (ROOT / "docs" / "WORKSPACE_DEPS.md").write_text(doc, encoding="utf-8")
    print(doc.split("## Details")[0])
